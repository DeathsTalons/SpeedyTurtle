// Bundles every migration into ONE file to paste into a brand-new Supabase project's SQL Editor,
// and marks that database as "test" so it can never be mistaken for the live one.
//
//   node scripts/build-test-database-sql.ts      (or: npm run db:test-setup)
//
// Writes supabase/test-database-setup.sql. Re-run it whenever a new migration is added.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "supabase", "migrations");
const files = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();

const parts = [
  "-- Redbird Grocery: TEST database setup. Generated by scripts/build-test-database-sql.ts; don't edit by hand.",
  "-- Paste ALL of this into the SQL Editor of a NEW, EMPTY Supabase project and click Run (once).",
  "-- Never run it on the live database: it would try to recreate tables that already exist and stop with an error.",
  "",
  ...files.flatMap((f) => [`-- ════════════ ${f} ════════════`, readFileSync(join(dir, f), "utf8").trim(), ""]),
  "-- ════════════ mark this database as TEST ════════════",
  "update settings set environment = 'test';",
  "",
];
const out = join(import.meta.dirname, "..", "supabase", "test-database-setup.sql");
writeFileSync(out, parts.join("\n"));
console.log(`Wrote ${out} from ${files.length} migrations.`);
